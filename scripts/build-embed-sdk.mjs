// path: scripts/build-embed-sdk.mjs
// Compiles the merchant checkout SDK (lib/payment/embed-sdk/client.ts, no imports) into one browser script,
// public/embed/v1/kd-checkout.js, that exposes window.KDCheckout. Uses the TypeScript compiler that is already installed.
//   node scripts/build-embed-sdk.mjs           writes the file
//   node scripts/build-embed-sdk.mjs --check   fails when the file is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'lib/payment/embed-sdk/client.ts');
const target = path.join(root, 'public/embed/v1/kd-checkout.js');

const compiled = ts.transpileModule(fs.readFileSync(source, 'utf8'), {
  compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.CommonJS, removeComments: true },
}).outputText;

const output = `// path: public/embed/v1/kd-checkout.js
// KD SOLUTION IT merchant checkout SDK. Generated by scripts/build-embed-sdk.mjs from lib/payment/embed-sdk/client.ts. Do not edit.
(function () {
"use strict";
var exports = {};
${compiled}
var api = { mount: exports.mountCheckout, mountAll: exports.mountAll };
window.KDCheckout = api;
if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", function () { api.mountAll(); });
else api.mountAll();
})();
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    process.stderr.write('RESULT [embed-sdk]: public/embed/v1/kd-checkout.js is out of date; run node scripts/build-embed-sdk.mjs\n');
    process.exit(1);
  }
  process.stdout.write('RESULT [embed-sdk]: ok\n');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, output);
  process.stdout.write(`embed-sdk: wrote ${path.relative(root, target)} (${output.length} bytes)\n`);
}
