export function isDisposableEmail(email: string): boolean {
  const at = email.lastIndexOf('@');
  if (at < 1) return false;
  const labels = email
    .slice(at + 1)
    .trim()
    .toLowerCase()
    .split('.');
  for (let i = 0; i < labels.length - 1; i++) {
    if (DOMAINS.has(labels.slice(i).join('.'))) return true;
  }
  return false;
}
